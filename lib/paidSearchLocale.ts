export function landingTranslator(locale: LandingLocale, extra: LandingTranslations = {}) {
  const dictionary = locale === "en" ? {} : { ...sharedLandingTranslations[locale], ...extra };
  return (text: string, values: Record<string, string | number> = {}) => {
    let translated = dictionary[text] ?? text;
    for (const [name, value] of Object.entries(values)) translated = translated.replaceAll(`{${name}}`, String(value));
    return translated;
  };
}
export function localizedTime(time: string, locale: LandingLocale) {
  if (locale === "en") return time;
  const match = /^(\d+):(\d+) (AM|PM)$/.exec(time);
  if (!match) return time;
  const hour = Number(match[1]) % 12 + (match[3] === "PM" ? 12 : 0);
  return new Intl.DateTimeFormat(localeTag(locale), { hour: "numeric", minute: "2-digit", timeZone: "UTC" }).format(new Date(Date.UTC(2026, 0, 1, hour, Number(match[2]))));
}
